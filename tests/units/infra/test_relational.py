def test_families_compare_numbers_together() -> None:
    integer, decimal_ = contract.TypeFamily.INTEGER, contract.TypeFamily.DECIMAL

    assert integer.comparable(decimal_)
    assert not integer.comparable(contract.TypeFamily.TEXT)
    assert not contract.TypeFamily.OTHER.comparable(contract.TypeFamily.OTHER)


