# SQLAlchemy's dialect modules are not typed.
mssql: Any = sa_mssql
oracle: Any = sa_oracle
postgresql: Any = sa_postgresql

TABLE = sa.Table(
    "t",
    sa.MetaData(),
    sa.Column("a", sa.Integer),
    sa.Column("b", sa.Unicode(10)),
    sa.Column("c", sa.Integer),
    sa.Column("doc", sa.UnicodeText),
)


def _sql(expression: Any, dialect: Any) -> str:
    return str(
        expression.compile(
            dialect=dialect, compile_kwargs={"literal_binds": True}
        )
    )


@pytest.mark.parametrize(
    ("dialect", "expected"),
    [
        (
            "mssql",
            [
                "CREATE TABLE etl_key_registry",
                "NVARCHAR(150)",
                "IDENTITY",
                (
                    "CREATE UNIQUE INDEX etl_quarantine_open ON etl_quarantine"
                    " (pipeline, record_key) WHERE status = N'open'"
                ),
            ],
        ),
        (
            "oracle",
            [
                "VARCHAR2(150 CHAR)",
                "GENERATED",
                "CLOB",
                (
                    "CREATE UNIQUE INDEX etl_quarantine_open ON etl_quarantine"
                    " (CASE WHEN (status = 'open') THEN pipeline END,"
                ),
            ],
        ),
        (
            "postgresql",
            [
                "VARCHAR(150)",
                "GENERATED BY DEFAULT AS IDENTITY",
                "WHERE status = 'open'",
            ],
        ),
        ("mysql", ["VARCHAR(150)", "AUTO_INCREMENT", "DOUBLE"]),
        ("sqlite", ["CREATE INDEX etl_quarantine_run"]),
    ],
)
def test_the_etl_tables_have_ddl_for_each_database(
    dialect: str, expected: list[str]
) -> None:
    ddl = relational.ddl(dialect)

    for fragment in expected:
        assert fragment in ddl
    # The 8 tables, and the version table, at the latest revision.
    assert ddl.count("CREATE TABLE") == 9
    assert "CREATE TABLE etl_alembic_version" in ddl
    assert "VALUES ('0004')" in ddl
    # MySQL has no partial index: its quarantine relies on reading first.
    assert ("etl_quarantine_open" in ddl) is (dialect != "mysql")


def test_ddl_takes_a_schema_and_a_prefix() -> None:
    ddl = relational.ddl("postgresql", schema="audit", prefix="mig_")

    assert "CREATE TABLE audit.mig_state" in ddl
    assert "CREATE TABLE audit.mig_alembic_version" in ddl


class TestKeyset:

    def test_expanded_where_row_values_are_missing(self) -> None:
        condition = dialects.MssqlDialect().after(
            [TABLE.c.a, TABLE.c.b, TABLE.c.c], [1, "x", 2]
        )

        assert _sql(condition, mssql.dialect()) == (
            "t.a >= 1 AND (t.a > 1 OR t.b >= N'x' AND (t.b > N'x' OR t.c > 2))"
        )

    def test_one_column(self) -> None:
        condition = dialects.OracleDialect().after([TABLE.c.a], [1])

        assert _sql(condition, oracle.dialect()) == "t.a > 1"

    def test_row_values_on_postgres(self) -> None:
        condition = dialects.PostgresDialect().after(
            [TABLE.c.a, TABLE.c.b], [1, "x"]
        )

        assert _sql(condition, postgresql.dialect()) == "(t.a, t.b) > (1, 'x')"


class TestChanged:

    def test_sql_server_compares_text_case_sensitively(self) -> None:
        stage = TABLE.alias("s")
        changed = dialects.MssqlDialect().changed(TABLE.c.b, stage.c.b)

        assert "COLLATE Latin1_General_100_BIN2" in _sql(
            changed, mssql.dialect()
        )

    def test_oracle_compares_lobs_with_dbms_lob(self) -> None:
        stage = TABLE.alias("s")
        lob = dialects.OracleDialect().changed(TABLE.c.doc, stage.c.doc)
        plain = dialects.OracleDialect().changed(TABLE.c.a, stage.c.a)

        assert "dbms_lob.compare(t.doc, s.doc) != 0" in _sql(
            lob, oracle.dialect()
        )
        assert _sql(plain, oracle.dialect()) == "DECODE(t.a, s.a, 0, 1) = 1"


def test_each_database_gets_its_dialect() -> None:
    def name(url: str) -> str:
        return dialects.for_engine(sa.create_engine(url)).name

    assert name("sqlite://") == "generic"
    assert name("postgresql+psycopg://x@h/d") == "postgresql"
    assert name("oracle+oracledb://x@h/d") == "oracle"
    assert name("mssql+mssqlpython://x@h/d") == "mssql"


def test_uuids_given_as_text_are_coerced_for_uuid_columns() -> None:
    table = sa.Table(
        "k",
        sa.MetaData(),
        sa.Column("id", sa.Uuid),
        sa.Column("label", sa.Unicode(36)),
    )
    text = str(uuid.UUID(int=1))

    (row,) = dialects.coerce(table, [{"id": text, "label": text}])

    assert row == {"id": uuid.UUID(int=1), "label": text}


