@pytest.mark.parametrize(
    "message",
    [
        "duplicate key value violates unique constraint (SQLSTATE 23505)",
        (
            "[SQL Server]Violation of PRIMARY KEY constraint 'PK_x'. Cannot"
            " insert duplicate key in object 'dbo.t'."
        ),
        "ORA-00001: unique constraint (ETL.PK) violated",
        "(1062, \"Duplicate entry '1' for key 'PRIMARY'\")",
        "UNIQUE constraint failed: t.id",
    ],
)
def test_duplicate_keys_are_told_apart_on_every_database(message: str) -> None:
    error = sa_exc.IntegrityError("INSERT", {}, Exception(message))

    assert dialects.is_unique_violation(error)


def test_other_constraints_are_not_duplicate_keys() -> None:
    error = sa_exc.IntegrityError(
        "INSERT", {}, Exception("FOREIGN KEY constraint failed")
    )

    assert not dialects.is_unique_violation(error)
    assert not dialects.is_unique_violation(None)


def test_a_connection_out_when_the_database_is_closed_is_closed(
    tmp_path: pathlib.Path,
) -> None:
    # Pooled, it went back to the disposed pool, never closed: the garbage
    # collector warned of an unclosed database, at a later test.
    db = relational.Database(f"sqlite:///{tmp_path / 'etl.db'}")

    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        with db.connect("reading") as connection:
            connection.execute(sa.select(1))
            db.close()
        del connection
        gc.collect()

    assert [str(w.message) for w in caught] == []
    assert isinstance(db.engine.pool, sa.pool.NullPool)
    # In memory, the database lives in its connection: kept pooled.
    memory = relational.Database("sqlite://")
    assert not isinstance(memory.engine.pool, sa.pool.NullPool)
    memory.engine.dispose()
